//! The unit a table or index name's length is counted in, position by
//! position.
//!
//! DynamoDB counts the length of a name in UTF-16 units in some positions and
//! in characters in others; never in UTF-8 bytes. Only a name with a
//! non-ASCII character can tell the units apart, and such a name always breaks
//! the name pattern too, so what changes is which faults the refusal lists.
//!
//! `ROWS` holds twelve names in eighteen positions, sent to DynamoDB in
//! eu-west-2 and us-east-1 on 12 November 2026, with the answer each region
//! gave. No table existed for any of them. They are data captured from
//! DynamoDB, not written by hand. The names are `e2`, `e200`, `e255` and
//! `e256`, that many `é` (one UTF-16 unit, two bytes each); `m2`, `m127`,
//! `m128`, `m255` and `m256`, that many `😀` (two UTF-16 units, four bytes
//! each); `ae`, which is `aé`; and `a2` and `a256`, which are ASCII. A long
//! name is written in the data as its label in angle brackets (`<m256>`) and
//! spelled out before it is sent or compared.
//!
//! Where the regions differ, which they do only in the order of the same two
//! faults, eu-west-2's answer is asserted and us-east-1's is held beside it.
//! DynamoDB's order of the length and pattern faults isn't stable: on a
//! CreateTable global index name it differs from name to name within
//! eu-west-2, and a capture across every region on 5 November 2026 saw the
//! same split. Dynoxide lists them in one fixed order per position, the order
//! eu-west-2 gives most often there. A row eu-west-2 answered in the other
//! order holds both orders, and passes with either.
//!
//! Every row is sent, in order, to one server with no tables, and each answer
//! is compared with DynamoDB's as JSON, along with the HTTP status. A row in
//! `LEFT_OUT` is still sent, and must give the answer it gives today, which
//! differs from DynamoDB's, for the reason given there.

#![cfg(feature = "http-server")]

use dynoxide::Database;

/// One captured request: where the name sits, which name it is, the
/// operation and body, and the answers.
struct Row {
    /// The position the name is in, such as `CreateTable.GSI` for a global
    /// secondary index's name on CreateTable.
    position: &'static str,
    /// The name's label.
    name: &'static str,
    operation: &'static str,
    body: &'static str,
    /// eu-west-2's answer, the one asserted.
    eu_west_2: &'static str,
    /// us-east-1's answer, where it differs from eu-west-2's.
    us_east_1: Option<&'static str>,
    /// eu-west-2's answer with its two faults the other way round, for a row
    /// eu-west-2 answered in the order Dynoxide doesn't use at that position.
    other_order: Option<&'static str>,
}

/// A row left out of the comparison, with why and the answer it gets today.
struct LeftOut {
    position: &'static str,
    name: &'static str,
    reason: &'static str,
    today: &'static str,
}

/// The long names, by the label the data writes them as.
const LONG_NAMES: [(&str, char, usize); 8] = [
    ("<e200>", 'é', 200),
    ("<e255>", 'é', 255),
    ("<e256>", 'é', 256),
    ("<m127>", '😀', 127),
    ("<m128>", '😀', 128),
    ("<m255>", '😀', 255),
    ("<m256>", '😀', 256),
    ("<a256>", 'a', 256),
];

/// `text` with each long name's label spelled out.
fn spelled_out(text: &str) -> String {
    let mut text = text.to_string();
    for (label, c, count) in LONG_NAMES {
        text = text.replace(label, &c.to_string().repeat(count));
    }
    text
}

/// `text` with each long name written as its label again, longest first, so
/// a failure stays readable.
fn labelled(text: &str) -> String {
    let mut text = text.to_string();
    let mut names = LONG_NAMES;
    names.sort_by_key(|&(_, _, count)| std::cmp::Reverse(count));
    for (label, c, count) in names {
        text = text.replace(&c.to_string().repeat(count), label);
    }
    text
}

fn json(text: &str) -> serde_json::Value {
    serde_json::from_str(&spelled_out(text)).unwrap()
}

async fn start_server() -> String {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let url = format!("http://{}", listener.local_addr().unwrap());
    let db = Database::memory().unwrap();
    tokio::spawn(async move {
        dynoxide::server::serve_on(listener, db).await;
    });
    tokio::time::sleep(std::time::Duration::from_millis(50)).await;
    url
}

/// The HTTP status and the body of the answer to a request.
async fn answer(url: &str, operation: &str, body: &str) -> (u16, serde_json::Value) {
    let response = reqwest::Client::new()
        .post(url)
        .header("x-amz-target", format!("DynamoDB_20120810.{operation}"))
        .header("content-type", "application/x-amz-json-1.0")
        .header(
            "authorization",
            "AWS4-HMAC-SHA256 Credential=fakekey/20260101/eu-west-2/dynamodb/aws4_request, \
             SignedHeaders=host;x-amz-date;x-amz-target, Signature=fakesig",
        )
        .header("x-amz-date", "20260101T000000Z")
        .body(body.to_string())
        .send()
        .await
        .unwrap();
    let status = response.status().as_u16();
    (status, response.json().await.unwrap())
}

/// Every captured answer is an error, which DynamoDB sends with a 400.
const ERROR_STATUS: u16 = 400;

/// Every row gets eu-west-2's answer, or the other order where a row holds
/// both, apart from the rows in `LEFT_OUT`, which get the answer they get
/// today. The counts of rows sent, compared, holding two orders and left out
/// are printed and pinned.
#[tokio::test]
async fn every_name_is_counted_in_dynamodb_unit_for_its_position() {
    let url = start_server().await;
    let mut sent = 0;
    let mut compared = 0;
    let mut two_orders = 0;
    let mut left_out = 0;
    let mut wrong = Vec::new();
    for row in ROWS {
        sent += 1;
        let (status, got) = answer(&url, row.operation, &spelled_out(row.body)).await;
        let expected = json(row.eu_west_2);
        let at = format!("{} {}", row.position, row.name);
        let shown = labelled(&got.to_string());
        if let Some(out) = LEFT_OUT
            .iter()
            .find(|out| out.position == row.position && out.name == row.name)
        {
            left_out += 1;
            if got == expected && status == ERROR_STATUS {
                wrong.push(format!(
                    "{at}: left out ({}) but now matches DynamoDB: move it back",
                    out.reason
                ));
            } else if got != json(out.today) || status != ERROR_STATUS {
                wrong.push(format!(
                    "{at}: left out ({})\n  answered {status} {shown}\n  where it answered {}",
                    out.reason, out.today
                ));
            }
            continue;
        }
        compared += 1;
        let other = row.other_order.map(json);
        if other.is_some() {
            two_orders += 1;
        }
        if status != ERROR_STATUS || (got != expected && Some(&got) != other.as_ref()) {
            wrong.push(format!(
                "{at}\n  expected {ERROR_STATUS} {}\n  got      {status} {shown}",
                row.eu_west_2
            ));
        }
    }
    println!(
        "{sent} rows sent: {compared} compared, {two_orders} of them holding two orders; \
         {left_out} left out"
    );
    assert!(
        wrong.is_empty(),
        "{} of {sent} rows wrong:\n{}",
        wrong.len(),
        wrong.join("\n")
    );
    assert_eq!(left_out, LEFT_OUT.len(), "a left-out row matches no row");
    assert_eq!((sent, compared, two_orders, left_out), COUNTS);
}

/// The two regions differ only in the order of the same two faults, and only
/// on the rows that hold us-east-1's answer.
#[test]
fn the_regions_differ_only_in_fault_order() {
    let faults = |answer: &str| {
        let message = json(answer)["message"].as_str().unwrap().to_string();
        let (head, rest) = message.split_once(": ").unwrap();
        let mut faults: Vec<String> = rest.split("; ").map(String::from).collect();
        faults.sort();
        (head.to_string(), faults)
    };
    let mut differing = 0;
    for row in ROWS {
        let Some(us_east_1) = row.us_east_1 else {
            continue;
        };
        differing += 1;
        assert_ne!(json(us_east_1), json(row.eu_west_2));
        assert_eq!(faults(us_east_1), faults(row.eu_west_2), "{}", row.name);
    }
    assert_eq!(differing, 10);
    for row in ROWS {
        if let Some(other) = row.other_order {
            assert_eq!(faults(other), faults(row.eu_west_2), "{}", row.name);
        }
    }
}

